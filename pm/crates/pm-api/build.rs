//! Embed the built proxy-manager web UI into the API binary.
//!
//! The UI is a separate Vite project (`pm/ui`). Building it is optional: when
//! `pm/ui/dist` is absent this script emits an empty asset table and the server answers `/` with an
//! explanatory page instead of failing the build. That keeps `cargo build --workspace` working for
//! anyone who only cares about the HTTP API.
//!
//! Assets are embedded rather than read from disk at runtime so a single `caddy-rs-pm` binary can
//! be copied onto a host with no extra files. Content-hashed filenames make the mapping stable for
//! the lifetime of a build, so a static table is enough.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let manifest_dir = PathBuf::from(
        std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is always set by cargo"),
    );
    let ui_dist = manifest_dir.join("../../ui/dist");
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR is always set by cargo"));

    let mut files: Vec<PathBuf> = Vec::new();
    if ui_dist.is_dir() {
        collect(&ui_dist, &mut files);
        // Track the directory itself (catches files added or removed) plus every file (catches
        // content changes, which is what a rebuilt bundle produces).
        println!("cargo:rerun-if-changed={}", ui_dist.display());
        for file in &files {
            println!("cargo:rerun-if-changed={}", file.display());
        }
    }

    let mut generated = String::new();
    generated.push_str("// @generated by pm/crates/pm-api/build.rs - do not edit.\n");
    let _ = writeln!(
        generated,
        "/// Whether a web UI bundle was embedded at build time."
    );
    let _ = writeln!(
        generated,
        "pub const EMBEDDED: bool = {};",
        !files.is_empty()
    );
    let _ = writeln!(
        generated,
        "/// Embedded UI assets as `(path, bytes, content-type)`."
    );
    let _ = writeln!(generated, "pub static ASSETS: &[(&str, &[u8], &str)] = &[");
    for file in &files {
        let route = route_for(&ui_dist, file);
        let content_type = content_type_for(file);
        let _ = writeln!(
            generated,
            "    ({:?}, include_bytes!({:?}), {:?}),",
            route,
            file.display().to_string(),
            content_type
        );
    }
    let _ = writeln!(generated, "];");

    let target = out_dir.join("ui_assets.rs");
    std::fs::write(&target, generated)
        .unwrap_or_else(|error| panic!("failed to write {}: {error}", target.display()));
}

fn collect(dir: &Path, files: &mut Vec<PathBuf>) {
    let entries = match std::fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(error) => panic!("failed to read {}: {error}", dir.display()),
    };
    for entry in entries {
        let entry = entry.unwrap_or_else(|error| panic!("failed to read entry: {error}"));
        let path = entry.path();
        if path.is_dir() {
            collect(&path, files);
        } else if path.is_file() {
            files.push(path);
        }
    }
    // Deterministic output regardless of filesystem ordering.
    files.sort();
}

/// Map a file under `dist` to the URL path the server answers on.
fn route_for(root: &Path, file: &Path) -> String {
    let relative = file.strip_prefix(root).unwrap_or_else(|error| {
        panic!(
            "{} is not under {}: {error}",
            file.display(),
            root.display()
        )
    });
    let mut route = String::from("/");
    for component in relative.components() {
        if !route.ends_with('/') {
            route.push('/');
        }
        route.push_str(&component.as_os_str().to_string_lossy());
    }
    if route.ends_with("index.html") {
        // Serve the shell at `/` as well as at `/index.html`.
        route = "/".to_owned();
        return route;
    }
    route
}

fn content_type_for(file: &Path) -> &'static str {
    match file
        .extension()
        .and_then(|extension| extension.to_str())
        .unwrap_or_default()
        .to_ascii_lowercase()
        .as_str()
    {
        "html" => "text/html; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "json" => "application/json",
        "map" => "application/json",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "gif" => "image/gif",
        "webp" => "image/webp",
        "ico" => "image/x-icon",
        "txt" => "text/plain; charset=utf-8",
        "woff" => "font/woff",
        "woff2" => "font/woff2",
        "wasm" => "application/wasm",
        _ => "application/octet-stream",
    }
}
