//! `caddy-rs` command-line interface.
//!
//! Command surface follows Caddy's CLI where it is meaningful for this build: `adapt`, `validate`,
//! `run`, `reload`, `stop`, `list-modules`, `version`, `build-info`, `environ`, `completion` and
//! `manpage`. `pki list`/`pki show`/`pki export` and `trust` expose
//! the local CA material persisted by automatic HTTPS (`<data-dir>/pki/authorities/<id>/`); see
//! `docs/compatibility/CADDYFILE.md` for the
//! supported configuration surface.
//!
//! # Shell completion installation
//!
//! `completion <shell>` prints a script; `completion install`, `completion uninstall` and
//! `completion status` manage per-user installation of those same scripts:
//!
//! ```text
//! caddy-rs completion bash|zsh|fish|powershell
//! caddy-rs completion install [--shell <SHELL>]... [--dry-run]
//! caddy-rs completion uninstall [--shell <SHELL>]... [--dry-run]
//! caddy-rs completion status
//! ```
//!
//! `install` without `--shell` installs every detected shell (see the detection rules below); with
//! `--shell` it installs exactly the named shells. `--shell` is repeatable and also accepts a
//! comma-separated list, and values are case-insensitive (`ZSH` is `zsh`). Unknown values are a
//! usage error that names the accepted set (`bash, zsh, fish, powershell`). `uninstall` without
//! `--shell` visits every target path — not only currently detected shells — so a file remains
//! removable after the user moves or removes their shell configuration.
//!
//! Target paths (`XDG_DATA_HOME`/`XDG_CONFIG_HOME` win when set):
//!
//! | Shell | Path |
//! |---|---|
//! | bash | `${XDG_DATA_HOME:-$HOME/.local/share}/bash-completion/completions/caddy-rs` |
//! | zsh | `${XDG_DATA_HOME:-$HOME/.local/share}/zsh/site-functions/_caddy-rs` |
//! | fish | `${XDG_CONFIG_HOME:-$HOME/.config}/fish/completions/caddy-rs.fish` |
//! | powershell | `${XDG_CONFIG_HOME:-$HOME/.config}/powershell/Completions/caddy-rs.ps1` |
//!
//! zsh uses the `site-functions` directory, which is on `$fpath` for standard distributions. Users
//! of Oh My Zsh may instead need `~/.oh-my-zsh/completions/_caddy-rs`; this command does not write
//! there by default but detects `~/.oh-my-zsh` as evidence that zsh is in use. PowerShell users
//! must dot-source the installed file from `$PROFILE` themselves, for example
//! `. "$HOME/.config/powershell/Completions/caddy-rs.ps1"`; this command never edits `$PROFILE` or
//! any shell rc file. Parent directories are created as needed.
//!
//! A shell counts as detected when one of these rules matches, in this order:
//!
//! * the basename of `$SHELL` is the shell name (`bash`, `zsh`, `fish`, or `pwsh`/`powershell` for
//!   PowerShell);
//! * bash: `~/.bashrc` or `~/.bash_completion` exists;
//! * zsh: `~/.oh-my-zsh` or `~/.zshrc` exists;
//! * fish: the fish config directory exists (`$XDG_CONFIG_HOME/fish`, else `~/.config/fish`);
//! * powershell: an executable `pwsh` is on `PATH`, or `~/.config/powershell` exists (the
//!   PowerShell config directory is also checked under `XDG_CONFIG_HOME` when that is set).
//!
//! Merely having a shell binary on `PATH` does not count for bash, zsh or fish: a binary without a
//! configuration would make `install` write a file that shell never reads. `status` names the rule
//! that matched for each detected shell. The one deliberate exception is PowerShell, where `pwsh`
//! on `PATH` is itself the evidence that the user installed and configured it.
//!
//! Every installed file starts with the marker line
//! `# generated by caddy-rs completion install; safe to delete with 'caddy-rs completion uninstall'`.
//! `uninstall` removes a file only when that marker is its first line; it refuses any other file
//! with exit code 1 and a message naming the path. `install` likewise refuses to overwrite a file
//! it does not own. Installation is idempotent: re-running over identical bytes reports
//! "already up to date" and writes nothing. `--dry-run` prints the same actions without creating,
//! updating or removing anything.
//!
//! `status` prints, per shell, whether it was detected, the rule that matched, the target path and
//! the state: `not installed` (no owned file), `installed` (bytes equal the current generated
//! script) or `stale` (marker owned, but the bytes differ, typically after a binary upgrade).
//! `status` exits 0 unless a path cannot be read.
//!
//! A future installer for a distribution package, container image or desktop app should invoke
//! `caddy-rs completion install` as the target user instead of hard-coding a single shell: that way
//! every detected shell is covered, and the marker/ownership contract keeps uninstall safe.
//! Running the command with elevated privileges (root, `docker exec -u root`, `sudo`) installs
//! files for root's home, not the user's; run it as the user who will use the shell.

