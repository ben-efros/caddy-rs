//! `completion install`, `completion uninstall` and `completion status`.
//!
//! The generated scripts are the same bytes `completion <shell>` prints; installation adds a
//! first-line marker so a later `uninstall` can prove that a file belongs to this tool before
//! removing it. Every path honours `XDG_DATA_HOME`/`XDG_CONFIG_HOME` when they are set and falls
//! back to the conventional home-directory locations otherwise. No shell rc file and no
//! PowerShell `$PROFILE` is ever read or written.

use std::env;
use std::ffi::OsStr;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use anyhow::{bail, Context, Result};

use crate::completion;

/// First line of every file written by `completion install`; ownership is proven by it.
///
/// The wording is deliberately actionable because users find these files by reading them, not by
/// reading this source file.
pub(crate) const MARKER: &str = "# generated by caddy-rs completion install; safe to delete with 'caddy-rs completion uninstall'";

/// The accepted `--shell` values, in the order used by every diagnostic.
const ACCEPTED: &str = "bash, zsh, fish, powershell";

/// The shells this command can install completions for.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Shell {
    Bash,
    Zsh,
    Fish,
    PowerShell,
}

/// Every shell, in the order `status` and a bare `uninstall` visit them.
const ALL: [Shell; 4] = [Shell::Bash, Shell::Zsh, Shell::Fish, Shell::PowerShell];

impl Shell {
    /// The lower-case name used in paths, scripts and output.
    fn name(self) -> &'static str {
        match self {
            Shell::Bash => "bash",
            Shell::Zsh => "zsh",
            Shell::Fish => "fish",
            Shell::PowerShell => "powershell",
        }
    }

    /// Parse one `--shell` value. Matching is ASCII case-insensitive.
    fn parse(value: &str) -> Result<Self> {
        match value.to_ascii_lowercase().as_str() {
            "bash" => Ok(Shell::Bash),
            "zsh" => Ok(Shell::Zsh),
            "fish" => Ok(Shell::Fish),
            "powershell" => Ok(Shell::PowerShell),
            _ => bail!("unknown shell `{value}` for --shell; accepted shells are: {ACCEPTED}"),
        }
    }

    /// Whether a `$SHELL` basename names this shell.
    fn matches_shell_env(self, basename: &str) -> bool {
        match self {
            Shell::PowerShell => basename == "pwsh" || basename == "powershell",
            other => basename == other.name(),
        }
    }

    /// The file `completion install` writes for this shell.
    fn target(self, layout: &Layout) -> PathBuf {
        match self {
            Shell::Bash => layout.data.join("bash-completion/completions/caddy-rs"),
            Shell::Zsh => layout.data.join("zsh/site-functions/_caddy-rs"),
            Shell::Fish => layout.config.join("fish/completions/caddy-rs.fish"),
            Shell::PowerShell => layout.config.join("powershell/Completions/caddy-rs.ps1"),
        }
    }
}

/// Where the installer reads and writes files, resolved once from the process environment.
///
/// Tests run the binary as a child with a fake `HOME`/XDG layout, which is why this type reads the
/// environment rather than a global.
struct Layout {
    home: PathBuf,
    data: PathBuf,
    config: PathBuf,
}

impl Layout {
    fn from_env() -> Result<Self> {
        let home = env_path("HOME").context(
            "cannot determine the home directory: HOME is not set, so completion paths are unknown",
        )?;
        let data = env_path("XDG_DATA_HOME").unwrap_or_else(|| home.join(".local/share"));
        let config = env_path("XDG_CONFIG_HOME").unwrap_or_else(|| home.join(".config"));
        Ok(Self { home, data, config })
    }
}

/// A non-empty environment variable as a path.
fn env_path(name: &str) -> Option<PathBuf> {
    env::var_os(name)
        .filter(|value| !value.is_empty())
        .map(PathBuf::from)
}

/// The result of the detection rules for one shell.
struct Detection {
    detected: bool,
    rule: Option<String>,
}

impl Detection {
    fn yes(rule: String) -> Self {
        Self {
            detected: true,
            rule: Some(rule),
        }
    }

    fn no() -> Self {
        Self {
            detected: false,
            rule: None,
        }
    }
}

/// Apply the documented detection rules, in order, and keep the rule that matched.
///
/// Being the basename of `$SHELL` is authoritative. Otherwise only a standard configuration artifact
/// counts: a shell binary on `PATH` is not evidence that the user configured that shell (PowerShell
/// is the documented exception, because `pwsh` only appears on `PATH` after an explicit install).
fn detect(shell: Shell, layout: &Layout) -> Detection {
    if let Some(value) = env::var_os("SHELL") {
        let path = PathBuf::from(&value);
        let basename = path.file_name().and_then(OsStr::to_str).unwrap_or_default();
        if shell.matches_shell_env(basename) {
            return Detection::yes(format!("$SHELL is {}", path.display()));
        }
    }

    match shell {
        Shell::Bash => {
            for candidate in [
                layout.home.join(".bashrc"),
                layout.home.join(".bash_completion"),
            ] {
                if candidate.exists() {
                    return Detection::yes(format!("{} exists", candidate.display()));
                }
            }
        }
        Shell::Zsh => {
            for candidate in [layout.home.join(".oh-my-zsh"), layout.home.join(".zshrc")] {
                if candidate.exists() {
                    return Detection::yes(format!("{} exists", candidate.display()));
                }
            }
        }
        Shell::Fish => {
            // The fish config directory is the standard marker. `$XDG_CONFIG_HOME` is honoured
            // first, then the literal `~/.config/fish` the documentation names.
            for candidate in [layout.config.join("fish"), layout.home.join(".config/fish")] {
                if candidate.is_dir() {
                    return Detection::yes(format!("{} exists", candidate.display()));
                }
            }
        }
        Shell::PowerShell => {
            if let Some(path) = executable_on_path("pwsh") {
                return Detection::yes(format!("{} is on PATH", path.display()));
            }
            for candidate in [
                layout.config.join("powershell"),
                layout.home.join(".config/powershell"),
            ] {
                if candidate.is_dir() {
                    return Detection::yes(format!("{} exists", candidate.display()));
                }
            }
        }
    }

    Detection::no()
}

/// Find an executable named `program` on `PATH`.
fn executable_on_path(program: &str) -> Option<PathBuf> {
    let paths = env::var_os("PATH")?;
    env::split_paths(&paths)
        .map(|directory| directory.join(program))
        .find(|candidate| is_executable(candidate))
}

fn is_executable(path: &Path) -> bool {
    let Ok(metadata) = fs::metadata(path) else {
        return false;
    };
    if !metadata.is_file() {
        return false;
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt as _;
        metadata.permissions().mode() & 0o111 != 0
    }
    #[cfg(not(unix))]
    {
        true
    }
}

/// Installation state of one target path, derived from its first line and its bytes.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum State {
    NotInstalled,
    Installed,
    Stale,
}

impl State {
    fn label(self) -> &'static str {
        match self {
            State::NotInstalled => "not installed",
            State::Installed => "installed",
            State::Stale => "stale",
        }
    }
}

/// What is on disk at one target path.
struct TargetState {
    state: State,
    /// A file exists but its first line is not [`MARKER`].
    foreign: bool,
}

/// Classify `path` against the currently generated script for `shell`.
fn inspect(path: &Path, shell: Shell) -> Result<TargetState> {
    let contents = match fs::read(path) {
        Ok(contents) => contents,
        Err(error) if error.kind() == io::ErrorKind::NotFound => {
            return Ok(TargetState {
                state: State::NotInstalled,
                foreign: false,
            });
        }
        Err(error) => {
            return Err(error).with_context(|| format!("cannot read `{}`", path.display()));
        }
    };

    if !is_owned(&contents) {
        return Ok(TargetState {
            state: State::NotInstalled,
            foreign: true,
        });
    }

    let expected = install_contents(shell)?;
    let state = if contents == expected.as_bytes() {
        State::Installed
    } else {
        State::Stale
    };
    Ok(TargetState {
        state,
        foreign: false,
    })
}

/// Whether the first line of `contents` is [`MARKER`].
fn is_owned(contents: &[u8]) -> bool {
    contents
        .split(|byte| *byte == b'\n')
        .next()
        .is_some_and(|first| first == MARKER.as_bytes())
}

/// The exact bytes `completion install` writes: the marker line followed by the generated script.
fn install_contents(shell: Shell) -> Result<String> {
    let script = completion::generate(shell.name())?;
    let mut contents = String::with_capacity(MARKER.len() + 1 + script.len());
    contents.push_str(MARKER);
    contents.push('\n');
    contents.push_str(&script);
    Ok(contents)
}

/// `completion install [--shell <shell>]... [--dry-run]`.
pub(crate) fn install(requested: &[String], dry_run: bool) -> Result<()> {
    let layout = Layout::from_env()?;
    let shells = select_shells(requested, &layout, Selection::Detected)?;
    for shell in shells {
        let target = shell.target(&layout);
        let contents = install_contents(shell)?;
        match fs::read(&target) {
            Ok(existing) if existing == contents.as_bytes() => {
                println!("{}: already up to date {}", shell.name(), target.display());
            }
            Ok(existing) => {
                if !is_owned(&existing) {
                    bail!(
                        "refusing to overwrite {}: existing file was not installed by caddy-rs \
                         (its first line is not the marker)",
                        target.display()
                    );
                }
                if dry_run {
                    println!("{}: would update {}", shell.name(), target.display());
                } else {
                    write_file(&target, &contents)?;
                    println!("{}: updated {}", shell.name(), target.display());
                }
            }
            Err(error) if error.kind() == io::ErrorKind::NotFound => {
                if dry_run {
                    println!("{}: would install {}", shell.name(), target.display());
                } else {
                    write_file(&target, &contents)?;
                    println!("{}: installed {}", shell.name(), target.display());
                }
            }
            Err(error) => {
                return Err(error).with_context(|| format!("cannot read `{}`", target.display()));
            }
        }
    }
    Ok(())
}

/// `completion uninstall [--shell <shell>]... [--dry-run]`.
///
/// Without `--shell` every known target path is visited, not just currently detected shells: a file
/// installed earlier stays removable after the user moves or removes their shell configuration.
pub(crate) fn uninstall(requested: &[String], dry_run: bool) -> Result<()> {
    let layout = Layout::from_env()?;
    let shells = select_shells(requested, &layout, Selection::All)?;
    let mut refused = Vec::new();
    for shell in shells {
        let target = shell.target(&layout);
        let contents = match fs::read(&target) {
            Ok(contents) => contents,
            Err(error) if error.kind() == io::ErrorKind::NotFound => {
                println!("{}: not installed {}", shell.name(), target.display());
                continue;
            }
            Err(error) => {
                return Err(error).with_context(|| format!("cannot read `{}`", target.display()));
            }
        };
        if !is_owned(&contents) {
            refused.push(format!(
                "refusing to remove {}: not installed by caddy-rs",
                target.display()
            ));
            continue;
        }
        if dry_run {
            println!("{}: would remove {}", shell.name(), target.display());
            continue;
        }
        fs::remove_file(&target)
            .with_context(|| format!("cannot remove `{}`", target.display()))?;
        println!("{}: removed {}", shell.name(), target.display());
    }
    if !refused.is_empty() {
        bail!("{}", refused.join("; "));
    }
    Ok(())
}

/// `completion status`.
pub(crate) fn status() -> Result<()> {
    let layout = Layout::from_env()?;
    for shell in ALL {
        let detection = detect(shell, &layout);
        let target = shell.target(&layout);
        let on_disk = inspect(&target, shell)?;
        println!("{}:", shell.name());
        match &detection.rule {
            Some(rule) => println!("  detected: yes ({rule})"),
            None => println!("  detected: no"),
        }
        println!("  target: {}", target.display());
        println!("  state: {}", on_disk.state.label());
        if on_disk.foreign {
            println!(
                "  note: the existing file is not owned by caddy-rs (first line is not the marker)"
            );
        }
    }
    Ok(())
}

/// Whether an absent `--shell` means "every detected shell" or "every known shell".
#[derive(Clone, Copy, PartialEq, Eq)]
enum Selection {
    Detected,
    All,
}

/// Resolve `--shell` values, or the documented default set when none were given.
fn select_shells(requested: &[String], layout: &Layout, default: Selection) -> Result<Vec<Shell>> {
    if requested.is_empty() {
        return match default {
            Selection::All => Ok(ALL.to_vec()),
            Selection::Detected => {
                let detected: Vec<Shell> = ALL
                    .iter()
                    .copied()
                    .filter(|shell| detect(*shell, layout).detected)
                    .collect();
                if detected.is_empty() {
                    bail!(
                        "no supported shell detected (checked {ACCEPTED}); \
                         set $SHELL or create a shell configuration, or pass --shell <name>"
                    );
                }
                Ok(detected)
            }
        };
    }

    let mut shells = Vec::new();
    for value in requested {
        let shell = Shell::parse(value)?;
        if !shells.contains(&shell) {
            shells.push(shell);
        }
    }
    Ok(shells)
}

/// Write `contents` to `path`, creating parent directories as needed.
fn write_file(path: &Path, contents: &str) -> Result<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
            .with_context(|| format!("cannot create directory `{}`", parent.display()))?;
    }
    fs::write(path, contents).with_context(|| format!("cannot write `{}`", path.display()))?;
    Ok(())
}
